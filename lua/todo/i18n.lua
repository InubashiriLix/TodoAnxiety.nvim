local M = {}

function M.t(key, ...)
    local lang = require("todo.config").get().language
    local value = (messages[lang] or messages.en)[key] or messages.en[key] or key
    if select("#", ...) > 0 then
        return string.format(value, ...)
    end
    return value
end

return M
