package.path = "./lua/?.lua;./lua/?/init.lua;" .. package.path
local core = require("todo.core")
assert(core.start())
local health = core.health()
assert(health.protocol == 1 and health.version, "core handshake")
local now = os.time()
local urgency = core.request("core.urgency", { { due_date = "2020-01-01", priority = 0 }, now })
assert(urgency.level == "overdue" and urgency.score == 150 and urgency.due_epoch, "core urgency")
assert(core.request("core.duration_parse", { "1h 30m" }) == 5400, "core duration")
assert(core.request("core.duration_parse", { "bad" }) == nil, "core invalid duration")
local rule = core.request("core.recurrence_normalize", { { kind = "weekly", weekdays = { 1, 3, 3 } } })
assert(vim.deep_equal(rule.weekdays, { 1, 3 }), "core recurrence dedup")
local next_at = core.request("core.recurrence_next", { { kind = "daily", every = 1 }, now, now })
assert(next_at and next_at > now, "core recurrence next")
assert(not pcall(core.request, "core.recurrence_normalize", { { kind = "bad" } }), "core invalid recurrence")
print("ok - mandatory Rust core handshake, urgency, duration and recurrence")
core.stop()
vim.cmd("qa!")
